#!/usr/bin/env python3
"""PreToolUse hook for Jarvis's workers (state/worker-settings.json names it).

Only acts inside Jarvis's own workers (env JARVIS_PROC=1); the owner's interactive sessions never see it.
  - Kill switch: while state/KILL exists in the data home, every tool call is refused ("stop everything").
  - Workers never send: a message, a comment, a canvas or an upload goes out only from the approvals worker, and only when
    it equals, word for word, a request the owner approved. Jarvis's own send code makes one call per run, with a ticket.
  - Credential stores are never read, and the server's write routes are never called from a worker's shell.
  - Shared records do not mention Claude, Jarvis or AI unless the owner allowed it in settings (sharing.ai_wording): a git
    commit message with an AI trailer or the words, a branch named claude/... or jarvis/..., or a ticket, page or draft text
    with those words is refused, with the reason, so the worker rewords it.
Exit 2 = refuse (stderr goes back to the worker); exit 0 = allow. Never raises: a broken hook must not stop the work.

This file stands alone on purpose: it uses the standard library only and never imports the Jarvis package, so nothing that
goes wrong in the package can switch the guard off. It finds the data home the same way jarvis/paths.py does (a test
holds the two together).
"""
import glob, json, os, re, sys

HOME = os.path.expanduser(os.environ.get('JARVIS_HOME') or os.path.join('~', '.jarvis'))
AI_ALLOWED = os.environ.get('JARVIS_AI_WORDING') == 'allowed'      # set by the server at its start, from settings

# tests point the hook at their own kill file (a worker cannot change its parent's environment, so this is not a way out)
KILL = os.environ.get('JARVIS_KILL_FILE_TEST') or os.path.join(HOME, 'state', 'KILL')
APPROVALS = os.path.join(HOME, 'approvals.json')
SEND_TOOLS = re.compile(r"(slack_send_message$|slack_schedule_message$|outlook_send_mail|outlook_send_draft|outlook_forward_mail|teams_send_chat_message|"
                        r"teams_send_channel_message|teams_reply_channel_message)", re.I)
JIRA_WRITE = re.compile(r"addCommentToJiraIssue$", re.I)
ATTACHED = re.compile(r'^Attached:\s*(.+?)\s*<?(https://[a-z0-9-]+\.slack\.com/docs/\S+?)>?$', re.I)
CANVAS = re.compile(r"slack_(create|update)_canvas$", re.I)
UPLOAD = re.compile(r"sharepoint_(upload_file|update_file|create_folder)$", re.I)
AI_WORDS = re.compile(r"co-authored-by:[^\n]*(claude|anthropic)|generated with \[?claude|\bclaude\b|\bjarvis\b|\banthropic\b|"
                      r"\bai[- ]generated\b|\bgenerated by (an )?ai\b|\bas an ai\b|🤖", re.I)
AI_BRANCH = re.compile(r"(?:^|[\s:/'\"])(?:claude|jarvis|ai)/[\w.-]+", re.I)
SHARED_TOOLS = re.compile(r"(createJiraIssue|editJiraIssue|addCommentToJiraIssue|addWorklogToJiraIssue|createConfluencePage|"
                          r"updateConfluencePage|createConfluence\w*Comment|slack_send_message_draft|slack_send_message|"
                          r"slack_create_canvas|slack_update_canvas|outlook_create\w*draft|teams_\w*message)", re.I)


DENIALS = os.path.join(HOME, 'state', 'denials')
MAX_CONSEC, MAX_TOTAL = 3, 20          # a worker refused this often is confused or being steered; it stops


def _count(refused):
    """Per task: refusals in a row and in total. Returns (consec, total)."""
    tid = os.environ.get('JARVIS_TASK_ID') or ('pid-' + str(os.getppid()))
    p = os.path.join(DENIALS, re.sub(r'[^\w.-]', '_', tid) + '.json')
    try:
        d = json.load(open(p))
    except (OSError, ValueError):
        d = {'consec': 0, 'total': 0}
    if not refused and not d['consec']:
        return 0, d['total']                      # nothing to reset: no write on the common path
    d['consec'] = d['consec'] + 1 if refused else 0
    d['total'] += 1 if refused else 0
    try:
        os.makedirs(DENIALS, exist_ok=True)
        json.dump(d, open(p, 'w'))
    except OSError:
        pass
    return d['consec'], d['total']


def stop_worker(reason):
    """End the whole run (not only this call): {"continue": false} on stdout, exit 0 (Claude Code reads JSON only on 0)."""
    print(json.dumps({'continue': False, 'stopReason': reason,
                      'hookSpecificOutput': {'hookEventName': 'PreToolUse', 'permissionDecision': 'deny', 'permissionDecisionReason': reason}}))
    sys.exit(0)


# A Bash command that READS a credential store is refused (the Read tool is denied in worker-settings.json;
# Bash is not covered by those rules). Running gcloud, aws or the DB helper is fine: they read their own login themselves.
CRED_PATHS = re.compile(r"(?:\b(?:cat|less|more|head|tail|strings|xxd|od|base64|cp|scp|rsync|grep|rg|awk|sed|python3?\s+-c|open)\b[^|;&\n]*"
                        r"(?:\.aws/credentials|\.config/gcloud/(?:credentials|access_tokens|legacy_credentials|application_default)|"
                        r"Library/Keychains|Library/Cookies|Application Support/Google/Chrome|\.netrc|\.git-credentials|pgpass|"
                        r"(?:^|[\s/])\.env(?:\.\w+)?\b))|\bsecurity\s+(?:find|dump)-(?:generic|internet)-password\b|\bsecurity\s+dump-keychain\b")


def refuse(msg):
    consec, total = _count(True)
    if consec >= MAX_CONSEC or total >= MAX_TOTAL:
        stop_worker(f'Stopped: {consec} refusals in a row, {total} in this run (last: {msg[:200]}). Jarvis tells the owner.')
    sys.stderr.write(msg + '\n')
    sys.exit(2)


def _norm(t):
    return re.sub(r'\s+', ' ', str(t or '')).strip()


def approved_match(name, inp):
    """True if (target, text) of this send equals an approved, not-yet-done request's payload."""
    try:
        items = json.load(open(APPROVALS)).get('items', [])
    except Exception:
        return False
    raw = str(inp.get('text') or inp.get('message') or inp.get('body') or inp.get('commentBody') or inp.get('content') or '')
    text = _norm(raw)
    target = str(inp.get('channel_id') or inp.get('channel') or inp.get('issueIdOrKey') or inp.get('issueKey') or inp.get('to') or '')
    for it in items:
        if it.get('status') not in ('approved', 'running'):
            continue
        p = it.get('payload') or {}
        want = _norm(p.get('text'))
        # The one addition the approvals skill makes: an "Attached: <title> <canvas link>" line per approved attachment
        # (without this the hook refuses every Send that carries a write-up, after the canvas was already made).
        if want and want != text:
            titles = {_norm(a.get('title')) for a in p.get('attachments') or [] if a.get('title')}
            lines = raw.rstrip().split('\n')
            while lines and (m := ATTACHED.match(lines[-1].strip())) and _norm(m.group(1)) in titles:
                lines.pop()
            text_wo = _norm('\n'.join(lines))
            if text_wo == want:
                text = want
        if not want or want != text:
            continue
        if JIRA_WRITE.search(name):
            if it.get('kind') == 'jira' and str(p.get('key')) == target:
                return True
        elif str(p.get('channel_id') or p.get('to') or '') == target or not target:
            return True
    return False


def approved_file(inp):
    """True if any value of the upload names an approved attachment's file (by its file name)."""
    vals = ' '.join(str(v) for v in inp.values() if isinstance(v, (str, int)))[:20000]
    try:
        items = json.load(open(APPROVALS)).get('items', [])
    except Exception:
        return False
    for it in items:
        if it.get('status') in ('approved', 'running'):
            for a in (it.get('payload') or {}).get('attachments') or []:
                base = os.path.basename(str(a.get('path') or ''))
                if base and base in vals:
                    return True
    return False


def approved_canvas(inp):
    title = _norm(inp.get('title') or inp.get('canvas_title') or '')
    try:
        items = json.load(open(APPROVALS)).get('items', [])
    except Exception:
        return False
    for it in items:
        if it.get('status') in ('approved', 'running'):
            for a in (it.get('payload') or {}).get('attachments') or []:
                if _norm(a.get('title')) == title and title:
                    return True
    return bool(inp.get('canvas_id')) and any(it.get('status') in ('approved', 'running') and (it.get('payload') or {}).get('attachments')
                                               for it in items)


AI_NAMES = re.compile(r'(?<![a-z0-9])(claude|jarvis|anthropic)(?![a-z0-9])', re.I)      # also at a line start, in _italics_


def strings(x):
    if isinstance(x, str):
        yield x
    elif isinstance(x, dict):
        for v in x.values():
            yield from strings(v)
    elif isinstance(x, list):
        for v in x:
            yield from strings(v)


def started_by_server():
    """True if the claude process running this hook was started directly by the Jarvis server (jarvis/slack_send.py), not
    by a worker's shell. Walks the process tree: hook -> (sh) -> claude -> a server pid in state/server-<port>.pid."""
    import subprocess
    servers = set()
    for f in glob.glob(os.path.join(HOME, 'state', 'server-*.pid')):
        try:
            servers.add(int(open(f).read().split()[0]))
        except Exception:
            pass
    if not servers:
        return False
    pid = os.getppid()
    for _ in range(4):
        try:
            out = subprocess.run(['ps', '-o', 'ppid=,comm=', '-p', str(pid)], capture_output=True, text=True, timeout=3).stdout.strip()
            ppid, comm = out.split(None, 1)
        except Exception:
            return False
        if os.path.basename(comm).startswith('claude'):
            return int(ppid) in servers
        pid = int(ppid)
    return False


SLACK_WRITE = re.compile(r"slack_(send_message|send_message_draft|schedule_message|create_canvas|update_canvas)$", re.I)
GENERIC_WRITE = re.compile(r"__(execute_?(write|destructive|mutation)\w*|\w*_?(delete|destroy|purge)\w*)$", re.I)
SLACK_READ = re.compile(r"slack_(read_\w+|search_\w+|get_reactions|list_channel_members)$")
SEND_LANE_TOOLS = re.compile(r"(slack_send_message|slack_send_message_draft|slack_create_canvas|slack_read_thread|slack_read_channel)$")


def send_lane(name, inp):
    """Jarvis's send code (jarvis/slack_send.py): one Slack call per run. A write must equal the ticket written just before
    (same tool, same arguments) and a ticket allows one call only, so nothing can go out twice or changed."""
    if name == 'ToolSearch' or (SEND_LANE_TOOLS.search(name) and 'read_' in name):
        return
    if not SEND_LANE_TOOLS.search(name):
        refuse('Refused: this run may only make the one Slack call it was given.')
    path = os.environ.get('JARVIS_SEND_TICKET') or ''
    if os.path.dirname(os.path.realpath(path)) != os.path.realpath(os.path.join(HOME, 'state', 'send')):
        refuse('Refused: no send ticket for this call.')
    if not started_by_server():
        refuse('Refused: only Jarvis itself can make this call.')
    try:
        t = json.load(open(path))
    except Exception:
        refuse('Refused: no send ticket for this call.')
    if t.get('used'):
        refuse('Refused: this call was already made once. Do not call it again; reply DONE.')
    if not name.endswith('__' + str(t.get('tool'))) or inp != t.get('args'):
        refuse('Refused: call the tool with exactly the arguments given, every character unchanged, nothing added.')
    if not AI_ALLOWED and any(AI_WORDS.search(v) or AI_NAMES.search(v) for v in strings(inp)):
        refuse('Refused: this text mentions Claude, Jarvis or AI; shared records do not (the owner can allow it in settings).')
    t['used'] = True
    tmp = path + '.tmp'
    json.dump(t, open(tmp, 'w'), ensure_ascii=False)
    os.replace(tmp, path)


def main():
    if os.environ.get('JARVIS_PROC') != '1':
        return
    try:
        ev = json.load(sys.stdin)
    except Exception:
        return
    if os.path.exists(KILL):
        stop_worker('kill switch')
    name, inp = str(ev.get('tool_name') or ''), ev.get('tool_input') or {}
    if os.environ.get('JARVIS_LANE') == 'send':
        send_lane(name, inp)
        return
    # Workers never write to Slack: Jarvis's own send code (jarvis/slack_send.py) makes the Slack draft and sends.
    if SLACK_WRITE.search(name) or ('Slack' in name and name.startswith('mcp__') and not SLACK_READ.search(name)):
        refuse('Refused: workers never write to Slack. Leave the reply in the work entry (reply.text, channel, channel_id, '
               'thread_ts, attachments); Jarvis puts it in their Slack drafts and sends it when they press Send.')
    # Generic write tools of any connector (some connectors have an executeWrite or executeDestructive that writes
    # anything; named-tool rules would not catch them). Never from a worker, in any lane.
    if name.startswith('mcp__') and GENERIC_WRITE.search(name):
        refuse('Refused: workers never use a connector\'s generic write or delete tool. Read only; anything that changes a '
               'shared system goes in the work entry for the owner\'s press.')
    if name == 'Bash':
        cmd = str(inp.get('command') or '')
        if re.search(r'page\.key|jarvis-page-key', cmd):
            refuse('Refused: the Jarvis page key is not for workers.')
        if CRED_PATHS.search(cmd):
            refuse('Refused: credential stores (cloud credential files, keychains, browser profiles, .env, pgpass, .netrc) are '
                   'never read by workers. Use the tool that needs them (gcloud, the DB helper) and let it read its own login.')
        # the server's outward routes, whatever port it listens on (they also need the page key; this stops the attempt)
        if re.search(r'/api/(approvals_add|approvals_set|jira/|slack_send|slack_leftover|ladder_raise|forge_promote|skill_decide)', cmd) or \
                (re.search(r'(localhost|127\.0\.0\.1)(:\d+)?', cmd) and re.search(r'slack_send|approvals_', cmd)):
            refuse('Refused: sends, approvals and ticket writes need the owner\'s press in the Jarvis page. Add a '
                   'pending request to approvals.json instead (the skill says how) and stop there.')
        if not AI_ALLOWED and re.search(r'\bgit\b[^\n]*\bcommit\b', cmd) and AI_WORDS.search(cmd):
            refuse('Commit refused: shared records never mention Claude, Jarvis or AI (no Co-Authored-By trailer either). '
                   'Write the commit message about the change itself and commit again.')
        if not AI_ALLOWED and re.search(r'\bgit\b[^\n]*\b(push|checkout|switch|branch|worktree)\b', cmd) and AI_BRANCH.search(cmd):
            refuse('Branch name refused: shared branches never mention Claude, Jarvis or AI. Name it for the work itself '
                   '(for example fix/login-timeout, or <ticket>-<short-slug>) and run it again.')
        return
    # Sends: only the operator (the approvals worker) may send, and only exactly what the owner approved:
    # the channel and the text must match an approved request in approvals.json word for word.
    if CANVAS.search(name):
        if os.environ.get('JARVIS_LANE') != 'operator':
            refuse('Refused: no canvases while drafting. Record the write-up (or Excel/CSV) in reply.attachments '
                   '[{"title", "path"}]; when the owner presses Send, the canvas is created and linked with the message.')
        if not approved_canvas(inp):
            refuse('Refused: a canvas may only be an attachment of a request the owner approved (same title as in approvals.json).')
    if UPLOAD.search(name):
        if os.environ.get('JARVIS_LANE') != 'operator':
            refuse('Refused: no uploads while drafting. Record the file in reply.attachments [{"title", "path"}]; when the owner '
                   'presses Send it goes to the shared folder and the link is added to the message.')
        if 'upload' in name.lower() and not approved_file(inp):
            refuse('Refused: only a file attached to a request the owner approved may be uploaded (approvals.json attachments).')
    if SEND_TOOLS.search(name) or JIRA_WRITE.search(name):
        if os.environ.get('JARVIS_LANE') != 'operator':
            refuse('Refused: workers never send messages or post comments; draft it (Slack draft or the work entry) and the owner sends it.')
        if not approved_match(name, inp):
            refuse('Refused: this is not exactly what the owner approved (channel/ticket and text must match an approved request in '
                   'approvals.json word for word). Send only the approved payload, unchanged.')
    if SHARED_TOOLS.search(name):
        text = json.dumps(inp, ensure_ascii=False)
        if not AI_ALLOWED and AI_WORDS.search(text):
            refuse('Refused: this text goes to a shared place (Jira, Confluence, Slack, email or Teams) and mentions Claude, '
                   'Jarvis or AI. Rewrite it about the work itself, with no AI wording, and try again.')


if __name__ == '__main__':
    try:
        main()
        if os.environ.get('JARVIS_PROC') == '1':
            _count(False)                     # an allowed call ends a run of refusals
    except SystemExit:
        raise
    except Exception:
        pass
