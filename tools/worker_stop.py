#!/usr/bin/env python3
"""Acceptance checks when a worker tries to finish: no false "done".

Claude Code runs this as the worker's Stop hook (state/worker-settings.json). For an item task (lane asked or background,
with a round-up item), code checks what the worker left behind before it may stop:
  hard (the worker is sent back to fix them, at most twice):
    - the work entry for the item exists and was written during this run;
    - every own point of the item has a state, and a 'done' point says what was done (note or answer);
    - every file it cites (done_work, reply attachments) exists;
    - a point marked 'drafted' has a reply to show; a Slack reply has its conversation;
    - a check Jarvis started itself (an initiative) opens its summary with VERDICT: yes|partly|no;
    - an investigation step (no item) wrote its plan and progress, marked a step passed or stopped at a question / done.
    - proof before words: every number in the reply, summary, points and numbers list is tied to an output file or
      a receipt; a "same method as ..." sentence has every condition ticked (jarvis/proof.py);
  soft (recorded, never blocking):
    - a summary longer than 40 words.
The result is written to state/stopchecks/<task>.json; the dispatcher records it in the ledger when the task ends.
Exit 2 with the reason on stderr = "do not stop yet, fix this". A fault in a check, or in loading the package it needs,
is recorded and never blocks: a worker is not held because the checker broke.
"""
import datetime as dt, glob, json, os, re, sqlite3, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))   # the repository: a tool run by itself finds the package
try:
    from jarvis import paths
except Exception:                                    # the package cannot be loaded: nothing to check with, never a block
    sys.exit(0)

HUB = str(paths.home())
DB = os.path.join(HUB, 'state', 'jarvis.db')
OUT = os.path.join(HUB, 'state', 'stopchecks')
MAX_BLOCKS = 2


def task_row(tid):
    con = sqlite3.connect(DB, timeout=5)
    con.row_factory = sqlite3.Row
    r = con.execute('SELECT * FROM tasks WHERE id=?', (tid,)).fetchone()
    con.close()
    return dict(r) if r else None


def ts(s):
    try:
        return dt.datetime.fromisoformat(str(s)).timestamp()
    except (TypeError, ValueError):
        return 0.0


def numbers(text):
    """Numbers worth sourcing: 3+ digits, or a decimal (1,234 / 12.50 / 48213), as plain digit strings."""
    out = []
    for m in re.finditer(r'(?<![\w.])\$?(\d{1,3}(?:,\d{3})+|\d+\.\d+|\d{3,})(?![\w])', str(text or '')):
        n = m.group(1).replace(',', '')
        if not re.fullmatch(r'20\d\d', n):                  # a year is not a result
            out.append(n)
    return out


AI_WORDS = re.compile(r"co-authored-by:[^\n]*(claude|anthropic)|generated with \[?claude|\bclaude\b|\bjarvis\b|\banthropic\b|"
                      r"\bai[- ]generated\b|\bgenerated by (an )?ai\b|\bas an ai\b|🤖", re.I)
SAYS_ATTACHED = re.compile(r'\b(attached|breakdown below|see below|full breakdown|file:)\b', re.I)


def profiles(t):
    """The profiles the router gave this item (ledger 'routed'), or those the prompt names."""
    out = set(re.findall(r'profile-(analyst|coder|writer)', str(t.get('prompt') or '')))
    try:
        con = sqlite3.connect(DB, timeout=5)
        r = con.execute("SELECT data FROM events WHERE kind='routed' AND ref=? ORDER BY at DESC LIMIT 1",
                        (f"{t.get('rid')}|{t.get('aid')}",)).fetchone()
        con.close()
        if r:
            out |= set(json.loads(r[0]).get('profiles') or [])
    except Exception:
        pass
    return out


def _git(*a):
    import subprocess
    try:
        p = subprocess.run(['git', *a], capture_output=True, text=True, timeout=20)
        return p.returncode, p.stdout
    except Exception:
        return 1, ''


def coder_checks(w, hard, soft):
    """A recorded branch means code changed: tests passed, the diff was reviewed, the commit exists, the name is clean."""
    b = w.get('branch')
    if not isinstance(b, dict):
        return
    tests = w.get('tests')
    if not isinstance(tests, dict) or not tests.get('cmd'):
        hard.append('Code changed (a branch is recorded) but no test run is recorded. Run the tests and record tests: {"cmd", "passed", "failed"}.')
    elif int(tests.get('failed') or 0) > 0:
        hard.append(f"The recorded tests failed ({tests.get('failed')} failing). Fix them before finishing; never leave a branch with failing tests.")
    elif not int(tests.get('passed') or 0):
        hard.append('The recorded test run passed nothing (passed: 0). Run the tests that cover the change, or write a focused one.')
    if not isinstance(w.get('code_review'), dict):
        hard.append('No code review is recorded. Review your own diff with the code-review skill, fix what it finds, and record code_review: {"findings", "fixed", "notes"}.')
    name = str(b.get('name') or '')
    if re.match(r'(claude|jarvis|ai)/', name, re.I):
        hard.append(f'The branch name {name} mentions an assistant. Name it for the work itself (<ticket>-<slug>).')
    repo, commit = os.path.expanduser(str(b.get('worktree') or b.get('repo') or '')), str(b.get('commit') or '')
    if repo and commit and os.path.isdir(repo):
        rc, _ = _git('-C', repo, 'cat-file', '-e', commit + '^{commit}')
        if rc != 0:
            hard.append(f'The recorded commit {commit[:12]} does not exist in {repo}. Record the real commit.')
        if b.get('base'):
            rc, out = _git('-C', repo, 'diff', '--name-only', f"{b['base']}...{commit}")
            if rc == 0 and len([x for x in out.splitlines() if x.strip()]) > 1 and not w.get('plan') and \
                    not glob.glob(os.path.join(HUB, 'work', 'outputs', '*', 'PLAN.md')):
                soft.append('more than one file changed and no PLAN.md')


def analyst_checks(w, rid, aid, cited, hard, soft):
    """Numbers come from a saved script."""
    folders = {os.path.join(HUB, 'work', 'outputs', f'{rid}-{aid}')} | {os.path.dirname(os.path.expanduser(str(p))) for p in cited if p and '/' in str(p)}
    scripts = [f for d in folders if os.path.isdir(d) for f in glob.glob(os.path.join(d, '**', '*'), recursive=True)
               if f.endswith(('.py', '.sql', '.ipynb', '.sh', '.r', '.R')) and os.path.isfile(f) and os.path.getsize(f) < 3_000_000]
    has_numbers = bool(w.get('numbers')) or len(numbers(w.get('summary'))) >= 2
    if has_numbers and not scripts:
        hard.append("The result has numbers but no script that produced them is saved in this item's outputs folder. Save it there (every number traces to a file).")
    if w.get('numbers') and not all(isinstance(n, dict) and n.get('what') for n in w['numbers'] if n):
        soft.append('numbers entries without "what"')


def writer_checks(w, hard, soft):
    """Shared text has no assistant wording; a reply that says "attached" or "below" really carries it."""
    r = w.get('reply') or {}
    text = str(r.get('text') or '')
    if not text.strip() or w.get('merged_into') or r.get('dropped'):
        return
    if os.environ.get('JARVIS_AI_WORDING') != 'allowed' and AI_WORDS.search(text):
        hard.append('The reply mentions Claude, Jarvis or AI. Shared text does not: rewrite it about the work itself.')
    if SAYS_ATTACHED.search(text) and not (r.get('attachments') or re.search(r'https?://', text) or '```' in text):
        hard.append('The reply says something is attached or below, but nothing is: add reply.attachments (or the content inline), or change the wording.')
    if len(text.split()) > 350:
        soft.append('reply over 350 words')
    # A chat message is a few plain sentences, or at most 3 short points; the detail goes in the attached file. Soft, not
    # hard: a nudge to trim.
    if str(r.get('channel') or 'slack') in ('slack', 'teams'):
        n_words = len(text.split())
        n_points = len(re.findall(r'(?m)^\s*(?:[-*\u2022]|\d+[.)])\s+', text))
        if 220 < n_words <= 350:
            soft.append(f'chat reply is {n_words} words: a few plain sentences is the rule, the detail in the attachment')
        if n_points > 3:
            soft.append(f'chat reply has {n_points} listed points: at most 3 short points is the rule')
    # Someone the owner listed as never to be named (settings: org.never_name, e.g. a person who has left).
    for name in _never_named():
        if re.search(r'(?<![A-Za-z])@?%s(?![A-Za-z])' % re.escape(name), text, re.I):
            hard.append(f'The reply names {name.capitalize()}, whom the owner listed as never to be named. Write their role, or leave the name out.')
    # Say each thing once: the same reply is not sent to the same conversation twice.
    try:
        rep = repeats(r, text)
    except Exception as e:
        rep = None; soft.append(f'repeat check could not run: {str(e)[:100]}')
    if rep and rep[0] >= 0.8:
        hard.append(f"This reply repeats what already went to the same conversation on {rep[1]} ({round(100 * rep[0])}% the same words). "
                    'Send only what is new or changed, and open with what it follows up ("following up on my ... note").')
    elif rep and rep[0] >= 0.55:
        soft.append(f'reply {round(100 * rep[0])}% the same words as the one sent to this conversation on {rep[1]}')


def _never_named():
    try:
        from jarvis import config
        return [str(w).strip().lower() for w in config.load().get('org.never_name') or [] if str(w).strip()]
    except Exception:
        return []


def repeats(r, text, days=14):
    """(likeness, date) of the most similar reply already sent to the same conversation in the last 14 days, or None.
    Same conversation = the same Slack channel and thread, or the same Jira ticket. Words only (slack_send.plain)."""
    from jarvis import slack_send
    jira = r.get('channel') == 'jira'
    key = (str(r.get('jira_key') or r.get('where') or '') if jira else (str(r.get('channel_id') or ''), str(r.get('thread_ts') or '')))
    if not key or key == ('', ''):
        return None
    cut = (dt.datetime.now().astimezone() - dt.timedelta(days=days)).isoformat(timespec='seconds')
    mine, best = slack_send.plain(text).split(), None
    if len(mine) < 12:
        return None
    import difflib
    for f in glob.glob(os.path.join(HUB, 'work', '20*.json')):
        if os.path.getmtime(f) < dt.datetime.now().timestamp() - (days + 2) * 86400:
            continue
        try:
            d = json.load(open(f))
        except (OSError, ValueError):
            continue
        for w in d.values():
            o = w.get('reply') if isinstance(w, dict) and isinstance(w.get('reply'), dict) else None
            if not o or o is r or not o.get('sent_at') or str(o['sent_at']) < cut:
                continue
            okey = (str(o.get('jira_key') or o.get('where') or '') if o.get('channel') == 'jira' else (str(o.get('channel_id') or ''), str(o.get('thread_ts') or '')))
            if (o.get('channel') == 'jira') != jira or okey != key:
                continue
            theirs = slack_send.plain(o.get('sent_full') or (o.get('send') or {}).get('text') or o.get('text') or '').split()
            if len(theirs) < 12 or theirs == mine and o.get('text') == r.get('text') and o.get('sent_at') == r.get('sent_at'):
                continue
            x = difflib.SequenceMatcher(None, mine, theirs, autojunk=False).ratio()
            if not best or x > best[0]:
                best = (x, str(o['sent_at'])[:10])
    return best


def investigation_checks(t):
    """One step of an investigation (world/investigate.py): the plan and progress were written in this run, one more
    step passes (or it stops at a question / done), a question is stated, a finished one has its brief."""
    con = sqlite3.connect(DB, timeout=5)
    con.row_factory = sqlite3.Row
    r = con.execute('SELECT * FROM investigations WHERE task_id=?', (t['id'],)).fetchone()
    con.close()
    if not r:
        return [], []
    d = os.path.join(HUB, 'work', 'tasks', r['id'])
    hard, started = [], ts(t.get('started'))
    try:
        p = json.load(open(os.path.join(d, 'plan.json')))
    except (OSError, ValueError) as e:
        return [f"{d}/plan.json is missing or not valid JSON ({e.__class__.__name__}). Fix it, then finish."], []
    for f in ('plan.json', 'progress.md'):
        fp = os.path.join(d, f)
        if not os.path.exists(fp) or (started and os.path.getmtime(fp) + 120 < started):
            hard.append(f"{f} was not written in this run. Record the step there, then finish.")
    passed = sum(1 for s in p.get('steps') or [] if isinstance(s, dict) and s.get('passes'))
    if passed <= (r['passed'] or 0) and p.get('state') not in ('question', 'done'):
        hard.append("No step was marked passes:true (with 'found' and 'evidence'), and the plan is not at a question or done. Do the step and record it.")
    if p.get('state') == 'question' and not str(p.get('question') or '').strip():
        hard.append("state is 'question' but plan.json has no question. Write the exact question, who can answer it and why it blocks.")
    if p.get('state') == 'done' and not os.path.exists(os.path.join(d, 'brief.md')):
        hard.append("state is 'done' but there is no brief.md. Write it (at most 300 words, sourced).")
    return hard, []


def check(t):
    rid, aid = t.get('rid') or '', t.get('aid') or ''
    hard, soft = [], []
    if t.get('kind') == 'investigation':
        return investigation_checks(t)
    if not rid or not aid:
        return hard, soft
    try:
        w = json.load(open(os.path.join(HUB, 'work', rid + '.json'))).get(aid)
    except (OSError, ValueError):
        w = None
    if not isinstance(w, dict):
        return [f"There is no work entry for item {aid} in work/{rid}.json. Write it as the jarvis-inbox-work skill says, then finish."], soft
    started = ts(t.get('started'))
    if started and ts(w.get('updated')) + 120 < started:
        hard.append("The work entry was not updated in this run ('updated' is older than the run's start). Write what you did, then finish.")
    try:
        act = next(a for a in json.load(open(os.path.join(HUB, 'roundups', rid + '.json'))).get('actions', []) if a.get('id') == aid)
    except (OSError, ValueError, StopIteration):
        act = {}
    own = [f'{aid}.{i}' for i, p in enumerate(act.get('points') or []) if not (isinstance(p, dict) and p.get('waiting'))]
    pts = {p.get('key'): p for p in (w.get('points') or []) if isinstance(p, dict)}
    missing = [k for k in own if k not in pts or not pts[k].get('state')]
    if missing:
        hard.append(f"These points have no state in the work entry: {', '.join(missing)}. Give each one (done, drafted, decide, needs_you, queued...) with a one-line note.")
    empty_done = [k for k, p in pts.items() if p.get('state') == 'done' and not str(p.get('note') or p.get('answer') or '').strip()]
    if empty_done:
        hard.append(f"These points are 'done' but say nothing about what was done: {', '.join(empty_done)}. Add a one-line note.")
    r = w.get('reply') or {}
    cited = [d.get('path') for d in (w.get('done_work') or []) if isinstance(d, dict)] + [a.get('path') for a in (r.get('attachments') or []) if isinstance(a, dict)]
    gone = [p for p in cited if p and not str(p).startswith('http') and not re.match(r'[A-Z][A-Z0-9]+-\d+', str(p)) and '/' in str(p) and not os.path.exists(os.path.expanduser(str(p)))]
    if gone:
        hard.append(f"These cited files do not exist: {', '.join(gone[:5])}. Fix the path or remove the reference.")
    merged = bool(w.get('merged_into') or r.get('dropped'))         # merged into another item's reply: no text of its own
    if not merged and any(p.get('state') == 'drafted' for p in pts.values()) and not str(r.get('text') or '').strip() and r.get('channel') not in ('none',):
        hard.append("A point says 'drafted' but the entry has no reply text. Write reply.text, or change the point's state.")
    if r.get('channel') == 'slack' and str(r.get('text') or '').strip() and not re.fullmatch(r'[CDG][A-Z0-9]{6,}', str(r.get('channel_id') or '')):
        hard.append("The Slack reply has no conversation (reply.channel_id). Take it from the round-up item.")
    prof = profiles(t)
    coder_checks(w, hard, soft)                                         # any task that records a branch changed code
    if 'analyst' in prof or w.get('numbers'):
        analyst_checks(w, rid, aid, cited, hard, soft)
    writer_checks(w, hard, soft)                                        # every reply is shared text
    if t.get('origin') == 'initiative' and not re.match(r'\s*VERDICT:\s*(yes|partly|no)\b', str(w.get('summary') or ''), re.I):
        hard.append("This check's summary must open with 'VERDICT: yes', 'VERDICT: partly' or 'VERDICT: no', then a dash and one reason.")
    # proof before words: every number in the reply, the summary, the points and the numbers list is tied to an output file
    # or a receipt, and a "same method" sentence has its conditions ticked (jarvis/proof.py).
    try:
        from jarvis import proof
        pv = proof.verdict(rid, aid, w)
        if not pv['ok']:
            if proof.mode() == 'enforce':
                hard.append(proof.say(pv))
            else:
                soft.append(f"proof: {len(pv['untied'])} of {pv['claims']} numbers tied to no output")
    except Exception as e:                                # a fault in the check is recorded, never a false block
        soft.append(f'proof check could not run: {str(e)[:120]}')
    if len(str(w.get('summary') or '').split()) > 40:
        soft.append('summary over 40 words')
    return hard, soft


def run_check(start):
    """An inbox-wide work run: every item it wrote during this run gets the same checks."""
    t0 = ts(start)
    if not t0:
        return 0
    hard = []
    for f in glob.glob(os.path.join(HUB, 'work', '20*.json')):
        if os.path.getmtime(f) < t0 - 5:
            continue
        rid = os.path.basename(f)[:-5]
        try:
            d = json.load(open(f))
        except ValueError:
            continue
        for aid, w in d.items():
            if isinstance(w, dict) and not aid.startswith('_') and ts(w.get('updated')) >= t0 - 5:
                h, _ = check({'rid': rid, 'aid': aid, 'started': start, 'origin': 'spine'})
                hard += [f'{rid} {aid}: {x}' for x in h]
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, 'run-' + re.sub(r'[^0-9]', '', start)[:14] + '.json')
    try:
        rec = json.load(open(path))
    except (OSError, ValueError):
        rec = {'blocks': 0}
    rec.update(at=dt.datetime.now().astimezone().isoformat(timespec='seconds'), hard=hard, kind='run-work', start=start)
    if hard and rec.get('blocks', 0) < MAX_BLOCKS:
        rec['blocks'] = rec.get('blocks', 0) + 1
        json.dump(rec, open(path, 'w'), indent=1)
        sys.stderr.write('Not finished yet. Acceptance checks found:\n- ' + '\n- '.join(hard[:12]) + '\nFix these, then finish.\n')
        return 2
    rec['final'] = True
    json.dump(rec, open(path, 'w'), indent=1)
    return 0


def main():
    if os.environ.get('JARVIS_PROC') != '1' or os.environ.get('JARVIS_LANE') not in ('asked', 'background'):
        return 0
    tid = os.environ.get('JARVIS_TASK_ID') or ''
    try:
        ev = json.load(sys.stdin)
    except ValueError:
        ev = {}
    if not tid and os.environ.get('JARVIS_RUN_KIND') == 'work':
        return run_check(os.environ.get('JARVIS_RUN_START') or '')
    t = task_row(tid) if tid else None
    if not t:
        return 0
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, tid + '.json')
    try:
        rec = json.load(open(path))
    except (OSError, ValueError):
        rec = {'blocks': 0}
    hard, soft = check(t)
    rec.update(at=dt.datetime.now().astimezone().isoformat(timespec='seconds'), hard=hard, soft=soft, rid=t.get('rid'), aid=t.get('aid'))
    if hard and rec.get('blocks', 0) < MAX_BLOCKS:
        rec['blocks'] = rec.get('blocks', 0) + 1
        json.dump(rec, open(path, 'w'), indent=1)
        sys.stderr.write('Not finished yet. Acceptance checks found:\n- ' + '\n- '.join(hard) + '\nFix these, then finish.\n')
        return 2
    rec['final'] = True
    json.dump(rec, open(path, 'w'), indent=1)
    return 0


if __name__ == '__main__':
    sys.exit(main())
